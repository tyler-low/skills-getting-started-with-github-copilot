def test_signup_rejects_duplicate_participant():
    # Arrange
    activity_name = "Chess Club"
    email = activities[activity_name]["participants"][0]

    # Act
    response = client.post(
        f"/activities/{activity_name}/signup",
        params={"email": email},
    )

    # Assert
    assert response.status_code == 400
    assert response.json()["detail"] == "Participant already registered"
    assert activities[activity_name]["participants"].count(email) == 1


def test_signup_fills_last_available_slot():
    # Arrange
    activity_name = "Soccer Club"
    activity = activities[activity_name]
    activity["max_participants"] = 1
    email = "student@mergington.edu"

    # Act
    response = client.post(
        f"/activities/{activity_name}/signup",
        params={"email": email},
    )

    # Assert
    assert response.status_code == 200
    assert activity["participants"] == [email]


def test_signup_rejects_full_activity_without_mutating_participants():
    # Arrange
    activity_name = "Soccer Club"
    activity = activities[activity_name]
    activity["max_participants"] = 1
    activity["participants"].append("existing@mergington.edu")
    original_participants = activity["participants"].copy()

    # Act
    response = client.post(
        f"/activities/{activity_name}/signup",
        params={"email": "student@mergington.edu"},
    )

    # Assert
    assert response.status_code == 400
    assert response.json()["detail"] == "Activity is full"
    assert activity["participants"] == original_participants


def test_unregister_removes_participant():
    # Arrange
    activity_name = "Chess Club"
    email = activities[activity_name]["participants"][0]

    # Act
    response = client.delete(
        f"/activities/{activity_name}/signup",
        params={"email": email},
    )

    # Assert
    assert response.status_code == 200
    assert email not in activities[activity_name]["participants"]


